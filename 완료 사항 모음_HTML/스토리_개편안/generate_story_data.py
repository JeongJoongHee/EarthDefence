# ------------------------------------------------------------------ Jua TTF cmap 검사기
def load_ttf_codepoints(ttf_path):
    """외부 패키지 없이 TTF cmap(포맷 4 / 12)에서 지원 코드포인트 집합을 읽는다."""
    with open(ttf_path, 'rb') as f:
        data = f.read()
    num_tables = struct.unpack('>H', data[4:6])[0]
    cmap_off = None
    for i in range(num_tables):
        rec = 12 + i * 16
        tag = data[rec:rec + 4]
        if tag == b'cmap':
            cmap_off = struct.unpack('>I', data[rec + 8:rec + 12])[0]
            break
    if cmap_off is None:
        return set()
    n_sub = struct.unpack('>H', data[cmap_off + 2:cmap_off + 4])[0]
    cps = set()
    for i in range(n_sub):
        rec = cmap_off + 4 + i * 8
        pid, eid, off = struct.unpack('>HHI', data[rec:rec + 8])
        sub = cmap_off + off
        fmt = struct.unpack('>H', data[sub:sub + 2])[0]
        if fmt == 4:
            seg_count = struct.unpack('>H', data[sub + 6:sub + 8])[0] // 2
            end_base = sub + 14
            start_base = end_base + seg_count * 2 + 2
            for s in range(seg_count):
                ec = struct.unpack('>H', data[end_base + s * 2:end_base + s * 2 + 2])[0]
                sc = struct.unpack('>H', data[start_base + s * 2:start_base + s * 2 + 2])[0]
                if ec == 0xFFFF and sc == 0xFFFF:
                    continue
                for cp in range(sc, ec + 1):
                    cps.add(cp)
        elif fmt == 12:
            n_groups = struct.unpack('>I', data[sub + 12:sub + 16])[0]
            base = sub + 16
            for g in range(n_groups):
                sc, ec, _ = struct.unpack('>III', data[base + g * 12:base + g * 12 + 12])
                for cp in range(sc, ec + 1):
                    cps.add(cp)
    return cps


