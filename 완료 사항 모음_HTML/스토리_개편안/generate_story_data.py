def verify_all_glyphs(seqs, talks, str_add):
    cps = load_ttf_codepoints(FONT_TTF)
    missing = {}

    def check(label, txt):
        for ch in txt:
            if ch in ('\n', '\r', '\t'):
                continue
            if ord(ch) not in cps:
                missing.setdefault(ch, []).append(label)

    for sid, lines in seqs:
        for i, (_, txt) in enumerate(lines, 1):
            check(f'{sid}#{i}', txt)
    for i, (txt, _) in enumerate(talks, 1):
        check(f'talk#{i}', txt)
    for k, ko, _ in str_add:
        check(f'str:{k}', ko)
    return missing


